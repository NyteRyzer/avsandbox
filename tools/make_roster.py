# Generates data/roster.json. Each character: identity, stats, movement,
# a kit (primary / secondary / special / utility) and a costume "look".

def C(id, name, alias, side, show, home, bio, movement, primary, secondary, special, look,
      health=100, speed=1.0, power=1.0, strength=False, utility=None, fly_speed=1.0):
    d = dict(id=id, name=name, alias=alias, side=side, show=show, home=home, bio=bio,
             health=health, speed=speed, power=power, movement=movement, strength=strength,
             primary=primary, secondary=secondary, special=special, look=look)
    if utility:
        d["utility"] = utility
    if fly_speed != 1.0:
        d["fly_speed"] = fly_speed
    return d

def L(suit, accent, skin, hair, extras=(), **kw):
    d = dict(suit=suit, accent=accent, skin=skin, hair=hair, extras=list(extras))
    d.update(kw)
    return d

def A(kind, name, **k):
    d = dict(kind=kind, name=name)
    d.update(k)
    return d

def S(kind, name, **k):
    d = dict(kind=kind, name=name)
    d.update(k)
    return d

def E(kind, color, c2=None, size=0.15, **k):
    d = dict(kind=kind, c1=color, c2=c2 or color, size=size)
    d.update(k)
    return d

